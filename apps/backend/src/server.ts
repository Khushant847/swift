import { createApp } from './app';
import { env } from './config/env';
import { logger } from './lib/logger';
import { prisma } from './lib/prisma';

async function bootstrap() {
  const app = createApp();

  logger.info(`Starting API (env: ${env.NODE_ENV}) — connecting to database…`);
  try {
    await prisma.$connect();
    logger.info('✅ Database connected');
  } catch (err) {
    logger.error('❌ Database connection failed. Run `npm run db:push` first.', err);
    process.exit(1);
  }

  const server = app.listen(env.PORT, () => {
    logger.info(`🚀 Swift Instruments API running → ${env.PUBLIC_BASE_URL} (env: ${env.NODE_ENV})`);
    logger.info(`   readiness probe: ${env.PUBLIC_BASE_URL}/health/ready`);
    if (env.NODE_ENV === 'production' && env.MAIL_DRIVER === 'console') {
      // console driver discards mail — enquiry notifications and email MFA
      // codes would silently never arrive in production.
      logger.warn(
        '⚠️  MAIL_DRIVER=console in production: emails (enquiry notifications, MFA codes) are logged and DISCARDED. Set MAIL_DRIVER=smtp.',
      );
    }
    if (env.NODE_ENV === 'production' && /^https?:\/\/(localhost|127\.0\.0\.1|\[?::1\]?)/i.test(env.PUBLIC_BASE_URL)) {
      // Uploaded media URLs are stored host-relative (see lib/storage.ts), so
      // the site no longer depends on this value — but anything else that
      // prints an absolute link (emails, backups) would point at localhost.
      logger.warn(
        `⚠️  PUBLIC_BASE_URL is "${env.PUBLIC_BASE_URL}" in production — absolute links generated by the backend will point at localhost. Set it to your real public origin (e.g. https://api.example.com).`,
      );
    }
  });

  const shutdown = async (signal: string) => {
    logger.info(`${signal} received — shutting down gracefully`);
    server.close(async () => {
      await prisma.$disconnect();
      process.exit(0);
    });
    setTimeout(() => process.exit(1), 10_000).unref();
  };

  // Give a clear, actionable message instead of a raw uncaught exception when
  // the port is taken (e.g. another `npm run dev` is still running).
  server.on('error', (err: NodeJS.ErrnoException) => {
    if (err.code === 'EADDRINUSE') {
      logger.error(
        `Port ${env.PORT} is already in use. Stop the process using it (or change PORT in apps/backend/.env) and start the API again.`,
      );
    } else {
      logger.error('HTTP server error', err);
    }
    process.exit(1);
  });

  process.on('SIGINT', () => void shutdown('SIGINT'));
  process.on('SIGTERM', () => void shutdown('SIGTERM'));
  process.on('unhandledRejection', (r) => logger.error('Unhandled rejection', r));
  process.on('uncaughtException', (err) => {
    logger.error('Uncaught exception — exiting', err);
    process.exit(1);
  });
}

void bootstrap();
