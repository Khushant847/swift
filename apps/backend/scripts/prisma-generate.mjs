#!/usr/bin/env node
/**
 * Generate the Prisma client for the right database target.
 *
 * The app always imports `@prisma/client`, so the generated client has to live
 * in the default location (`node_modules/.prisma/client`). Which schema produced
 * it depends on the environment:
 *
 *   - Local dev / tests  → prisma/schema.prisma        (SQLite)
 *   - Vercel / prod      → prisma/schema.mysql.prisma  (MySQL 8+)
 *
 * `schema.mysql.prisma` sets a custom `output` (…/client-mysql) for the local
 * migration scripts, which would leave `@prisma/client` pointing at the SQLite
 * client. This script copies that schema to a gitignored file with the `output`
 * override removed, so `prisma generate` writes the MySQL client where the app
 * imports it. No secrets are read or printed.
 *
 * Usage:
 *   node scripts/prisma-generate.mjs            # auto: mysql on Vercel, else sqlite
 *   node scripts/prisma-generate.mjs mysql      # force MySQL
 *   node scripts/prisma-generate.mjs sqlite     # force SQLite
 *   PRISMA_TARGET=mysql npm run build           # same, via env
 */
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const backendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const requireFromBackend = createRequire(path.join(backendDir, 'package.json'));

const requested = (process.argv[2] || process.env.PRISMA_TARGET || '').trim().toLowerCase();
const target = requested || (process.env.VERCEL ? 'mysql' : 'sqlite');

if (target !== 'mysql' && target !== 'sqlite') {
  console.error(`[prisma-generate] Unknown target "${target}". Use "mysql" or "sqlite".`);
  process.exit(1);
}

const sourceSchema =
  target === 'mysql'
    ? path.join(backendDir, 'prisma', 'schema.mysql.prisma')
    : path.join(backendDir, 'prisma', 'schema.prisma');

if (!fs.existsSync(sourceSchema)) {
  console.error(`[prisma-generate] Schema not found: ${sourceSchema}`);
  process.exit(1);
}

let schemaPath = sourceSchema;
let tempDir = '';

if (target === 'mysql') {
  const original = fs.readFileSync(sourceSchema, 'utf8');
  const stripped = original.replace(/^[ \t]*output[ \t]*=[ \t]*"[^"]*"[ \t]*$/m, '');

  // Fail loudly instead of silently generating a client in the wrong place.
  if (stripped === original) {
    console.error(
      `[prisma-generate] Expected an "output = ..." line in ${sourceSchema} to strip, but found none. ` +
        `Update this script if the schema changed.`,
    );
    process.exit(1);
  }

  tempDir = path.join(backendDir, '.prisma-build');
  fs.mkdirSync(tempDir, { recursive: true });
  schemaPath = path.join(tempDir, 'schema.prisma');
  fs.writeFileSync(
    schemaPath,
    `// AUTO-GENERATED by scripts/prisma-generate.mjs — do not edit or commit.\n${stripped}`,
    'utf8',
  );
}

let prismaBin = '';
try {
  // Resolve the CLI from the workspace (hoisted) node_modules without npx.
  prismaBin = requireFromBackend.resolve('prisma/build/index.js');
} catch {
  prismaBin = '';
}

console.log(`[prisma-generate] target=${target} schema=${path.relative(backendDir, schemaPath)}`);

try {
  if (prismaBin) {
    execFileSync(process.execPath, [prismaBin, 'generate', '--schema', schemaPath], {
      cwd: backendDir,
      stdio: 'inherit',
    });
  } else {
    const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
    execFileSync(npx, ['--no-install', 'prisma', 'generate', '--schema', schemaPath], {
      cwd: backendDir,
      stdio: 'inherit',
    });
  }
} catch (err) {
  console.error('[prisma-generate] prisma generate failed.');
  process.exit(typeof err?.status === 'number' ? err.status : 1);
} finally {
  if (tempDir) fs.rmSync(tempDir, { recursive: true, force: true });
}

// Prove the client landed where the app imports it, and that it is the right
// provider — a mismatch here would only surface as a runtime crash on Vercel.
try {
  const clientEntry = requireFromBackend.resolve('@prisma/client');
  const generatedSchema = path.join(path.dirname(clientEntry), '..', '..', '.prisma', 'client', 'schema.prisma');
  if (fs.existsSync(generatedSchema)) {
    const generated = fs.readFileSync(generatedSchema, 'utf8');
    const provider = generated.match(/datasource[\s\S]*?provider\s*=\s*"([^"]+)"/)?.[1] ?? 'unknown';
    console.log(`[prisma-generate] @prisma/client provider=${provider}`);
    if (provider !== target) {
      console.error(
        `[prisma-generate] Provider mismatch: expected "${target}", generated "${provider}". ` +
          `A stale client from a previous build may be winning resolution.`,
      );
      process.exit(1);
    }
  }
} catch {
  console.warn('[prisma-generate] Could not verify @prisma/client output path; continuing.');
}
